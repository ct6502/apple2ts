/**
 * 6502 Assembly Demos for VERA on Apple II
 * Adapted from X16 Community Demos (https://github.com/X16Community/x16-demo)
 * Supports dynamic Slot assignment (Slot 2 $C200, Slot 4 $C400, etc.)
 */

import { parseAssembly } from "../../utility/assembler"

export interface VeraDemoBinary {
  startAddress: number
  code: string[]
  bytes: number[]
}

const hex = (val: number) => val.toString(16).toUpperCase()

