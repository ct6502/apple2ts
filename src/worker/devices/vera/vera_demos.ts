/**
 * Builds executable binary and disassembly for a given VERA demo.
 */
export const buildVeraDemo = (
  generator: (slot: number, start: number) => string[],
  slot = 2,
  startAddress = 0x2000
): VeraDemoBinary => {
  const code = generator(slot, startAddress)
  const bytes = parseAssembly(startAddress, code)
  return {
    startAddress,
    code,
    bytes
  }
}
