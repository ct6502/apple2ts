import {
  browserLanguageAliases,
  defaultLanguageFlag,
  languageFallbacks,
  languagePolicies,
  legacyLanguageAliases,
} from "./language-policies.mjs"

const serialized = value => JSON.stringify(value, null, 2)

const assertKnownLanguage = (languages, language, description) => {
  if (!languages.has(language)) {
    throw new Error(`${description} references missing catalog: ${language}`)
  }
}

export const createLanguageDefinitions = (
  catalogs,
  policies = languagePolicies,
) => {
  const languages = new Set(catalogs.map(({locale}) => locale))
  for (const locale of Object.keys(policies)) {
    assertKnownLanguage(languages, locale, "Language policy")
  }

  return catalogs
    .map(catalog => {
      const policy = policies[catalog.locale] ?? {}
      return {
        ...catalog,
        name: policy.name ?? catalog.locale,
        flag: policy.flag ?? defaultLanguageFlag,
        order: policy.order ?? Number.MAX_SAFE_INTEGER,
      }
    })
    .sort((left, right) => left.order - right.order
      || left.locale.localeCompare(right.locale))
}

export const createLanguageRegistrySource = (catalogs, {
  policies = languagePolicies,
  savedAliases = legacyLanguageAliases,
  browserAliases = browserLanguageAliases,
  fallbacks = languageFallbacks,
} = {}) => {
  const definitions = createLanguageDefinitions(catalogs, policies)
  const languages = new Set(definitions.map(({locale}) => locale))

  for (const [alias, language] of Object.entries(savedAliases)) {
    assertKnownLanguage(languages, language, `Saved-language alias ${alias}`)
  }
  for (const {range, language} of browserAliases) {
    assertKnownLanguage(languages, language, `Browser-language alias ${range}`)
  }
  for (const [language, fallback] of Object.entries(fallbacks)) {
    assertKnownLanguage(languages, language, "Language fallback")
    assertKnownLanguage(languages, fallback, `Language fallback for ${language}`)
    if (language === fallback) {
      throw new Error(`Language fallback cannot reference itself: ${language}`)
    }
  }

  const imports = definitions.map(({locale, exportName}) => (
    `import { ${exportName} } from "./${locale}"`
  )).join("\n")
  const definitionSource = definitions.map(({
    locale,
    exportName,
    name,
    flag,
  }) => `  { id: ${JSON.stringify(locale)}, name: ${JSON.stringify(name)}, flag: ${JSON.stringify(flag)}, catalog: ${exportName} },`)
    .join("\n")

  return `// Generated by npm run generate-i18n-catalogs. Do not edit directly.\n\n${imports}\n\nexport const languageDefinitions = [\n${definitionSource}\n] as const\n\nexport type RegisteredLanguage = (typeof languageDefinitions)[number]["id"]\n\nexport const legacySavedLanguageIds: Readonly<Record<string, RegisteredLanguage>> = ${serialized(savedAliases)}\n\nexport const browserLanguageAliases: readonly { range: string, language: RegisteredLanguage }[] = ${serialized(browserAliases)}\n\nexport const languageFallbacks: Partial<Record<RegisteredLanguage, RegisteredLanguage>> = ${serialized(fallbacks)}\n`
}
